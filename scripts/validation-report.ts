// Validation report (spec §7): runs every V-case and writes docs/validation.md and src/validation.json
// (the rows the app shows in "Assumptions & validation"). Refuses to write if any check fails.
// Run: npx tsx scripts/validation-report.ts
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHECKS, FD, FD_TOL, v16, type Check, type ValidationRow } from '../tests/helpers/validation';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** V16: run the model and IO unit tests and count them. */
function unitTests(): Check {
  const dir = mkdtempSync(join(tmpdir(), 'lotohms-v16-'));
  const out = join(dir, 'v16.json');
  try {
    try {
      execFileSync('npx', ['vitest', 'run', 'tests/model', 'tests/io', '--reporter=json', `--outputFile=${out}`], {
        cwd: root, stdio: 'ignore', env: { ...process.env, VALIDATION: '' },
      });
    } catch { /* failing tests exit non-zero; the counts below report them */ }
    const r = JSON.parse(readFileSync(out, 'utf8')) as { numPassedTests: number; numTotalTests: number; testResults: unknown[] };
    return v16(r.numPassedTests, r.numTotalTests, r.testResults.length);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const checks: Check[] = [];
for (const [id, fn] of CHECKS) {
  const t = performance.now();
  const c = fn();
  console.log(`${id.padEnd(5)} ${c.row.status.padEnd(18)} ${c.row.result}  (${((performance.now() - t) / 1000).toFixed(1)} s)`);
  checks.push(c);
}
const u = unitTests();
console.log(`V16   ${u.row.status.padEnd(18)} ${u.row.result}`);
checks.push(u);

const failed = checks.filter((c) => c.failures.length);
if (failed.length) {
  for (const c of failed) console.error(`FAIL ${c.row.id}:\n  ${c.failures.join('\n  ')}`);
  console.error('Not writing docs/validation.md or src/validation.json.');
  process.exit(1);
}
const ids = checks.map((c) => c.row.id);
if (new Set(ids).size !== ids.length) throw new Error(`duplicate row ids: ${ids}`);

const rows: ValidationRow[] = checks.map((c) => c.row);
writeFileSync(join(root, 'src/validation.json'), `${JSON.stringify(rows, null, 2)}\n`);

const STATUS: Record<ValidationRow['status'], string> = { pass: 'pass', 'deviation-recorded': '**deviation recorded**', 'not-validated': 'not validated' };
const esc = (s: string): string => s.replace(/\|/g, '\\|');
const md: string[] = [
  '# Validation',
  '',
  'Generated by `npx tsx scripts/validation-report.ts` (do not edit by hand). The same rows are in `src/validation.json` and appear in the app under "Assumptions & validation". Case definitions, computations and acceptance live in `tests/helpers/validation.ts`; `npm run test:validation` asserts them.',
  '',
  'Every geometry is checked against a closed form, an exact limit or a published reference (spec §7). Status:',
  '',
  '- **pass**: an exact limit, the solver\'s own convergence, or the reference\'s stated accuracy is met;',
  `- **deviation recorded**: the reference publishes no accuracy, or the result is outside it. Per the failed-validation policy (spec §5) it was investigated with an independent second reference (a finite-difference solve, below) and the convergence check; the second reference agrees with the solver within ${FD_TOL} %, so the solver holds and the measured deviation of the formula is shown here and on the page;`,
  '- **not validated**: no reference exists (solder mask: sensitivity only), or the feature is not in this build yet.',
  '',
  'Zero-thickness reference geometries (V3–V6, V9–V12) are hand-built cross-sections, not Stackup objects: the model refuses copper of thickness 0, and on an open side it turns the far copper of a test stackup into a "cut out" slab of dielectric that is not part of the reference geometry (it first made the 1e-6 mm-cover embedded line read −5.6 % against plain microstrip). A test checks that the hand-built stripline and microstrip equal the model\'s cross-sections.',
  '',
  '## Summary',
  '',
  '| ID | Test | Reference | Result | Acceptance | Status |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${esc(r.test)} | ${esc(r.reference)} | ${esc(r.result)} | ${esc(r.acceptance)} | ${STATUS[r.status]} |`),
  '',
  '## Details',
  '',
];
for (const c of checks) {
  md.push(`### ${c.row.id}: ${c.row.test}`, '', `Reference: ${c.row.reference}. Acceptance: ${c.row.acceptance}. Status: ${STATUS[c.row.status]}.`, '');
  if (c.detail.length) md.push(...c.detail, '');
  for (const n of c.notes) md.push(n, '');
}
md.push(
  '## Second reference: independent finite-difference solve',
  '',
  'A uniform-grid 5-point finite-difference Laplace solve (scipy sparse direct solve; zero-thickness strips as Dirichlet nodes; cell-centred εr; capacitance from the field energy; grounded rectangular box), written independently of this solver by the reviewer of the reference formulas. It is not part of the npm suite, so its values are pinned in `tests/helpers/validation.ts`. Each value is extrapolated to d → 0 (observed order 0.97–1.0 on three grids, so order 1). For CPW without backside metal the box truncation matters (box 3 → 6 → 12 mm: +0.35 % then +0.09 % on Z0), and slightly for CPWG (+0.10–0.14 % from box 3 to 6), so those values carry a box-size correction to an unbounded domain. Estimated uncertainty: ±0.1 % (offset stripline), ±0.2 % (embedded, box 3 × 2 mm uncorrected), ±0.3 % (CPW, CPWG).',
  '',
  '| Geometry | Parameters (mm) | FD Z0 (Ω) | FD εeff | Raw grid values (d = 0.01 / 0.005 / 0.0025 mm unless stated) |',
  '|---|---|---|---|---|',
  ...FD.offset.map((x) => `| offset stripline | W ${x.W}, H1 ${x.H1}, H2 ${x.H2}, εr ${x.er} | ${x.z} | ${x.er} | ${x.raw} |`),
  ...FD.embedded.map((x) => `| embedded microstrip | W 0.2, H 0.1, cover ${x.Hc}, εr 4.4 | ${x.z} | ${x.eeff} | ${x.raw} |`),
  ...FD.cpwOpen.map((x) => `| CPW, no backside metal | W ${x.W}, G ${x.G}, h ${x.h}, εr ${x.er} | ${x.z} | ${x.eeff} | ${x.raw} |`),
  ...FD.cpwg.map((x) => `| CPWG | W ${x.W}, G ${x.G}, h ${x.h}, εr ${x.er} | ${x.z} | ${x.eeff} | ${x.raw} |`),
  '',
);
writeFileSync(join(root, 'docs/validation.md'), md.join('\n'));
console.log(`Wrote docs/validation.md and src/validation.json (${rows.length} rows).`);
